/**
 * Static-site build for the Cash Kitty web app.
 *
 * Produces a fully static `dist/` (HTML + hashed JS/CSS + PWA assets) that can
 * be hosted on any static host (Cloudflare Pages / Netlify / Vercel) served at
 * the site root.
 *
 * Unlike `bun start`, there is NO server here: the OCR proxy (`/api/ocr/*`) and
 * the runtime config endpoint (`/api/config`) do not exist. The config the
 * server used to provide is instead baked into the bundle at build time from
 * `BUN_PUBLIC_*` env vars (see `.env.example`):
 *   - BUN_PUBLIC_GOOGLE_CLIENT_ID — Google OAuth web client id (Drive).
 *   - BUN_PUBLIC_OCR_API_URL      — OCR API base URL the SPA calls directly
 *                                   (e.g. a Cloudflare Tunnel fronting the local
 *                                   API). OCR works only while that endpoint is
 *                                   reachable, so it is effectively local-only.
 */
import { createHash } from "node:crypto";
import { cp, rm } from "node:fs/promises";
import { join, relative } from "node:path";
import tailwind from "bun-plugin-tailwind";

const root = import.meta.dir;
const outdir = join(root, "dist");

// Start from a clean output directory so stale hashed assets don't linger.
await rm(outdir, { recursive: true, force: true });

const result = await Bun.build({
	entrypoints: [join(root, "src/index.html")],
	outdir,
	target: "browser",
	minify: true,
	sourcemap: "linked",
	plugins: [tailwind],
	// Inline BUN_PUBLIC_* env vars (Google client id, OCR API URL) into the bundle.
	env: "BUN_PUBLIC_*",
	// frontend.tsx registers the service worker only in production builds.
	define: { "process.env.NODE_ENV": JSON.stringify("production") },
});

if (!result.success) {
	console.error("❌ Build failed:");
	for (const log of result.logs) console.error(log);
	process.exit(1);
}

// PWA assets (manifest, service worker, icons) are served from ../public by the
// Bun server at runtime; a static host needs them copied to the site root.
await cp(join(root, "public"), outdir, { recursive: true });

// Stamp the service worker with a per-build version and precache list so every
// deploy installs a fresh cache (and `activate` purges the old one). Without
// this the cache name is constant, the stale shell keeps pointing at hashed
// assets that no longer exist on the server, and the PWA renders blank.
await injectServiceWorkerVersion();

async function injectServiceWorkerVersion(): Promise<void> {
	const swPath = join(outdir, "sw.js");
	if (!(await Bun.file(swPath).exists())) {
		console.warn("⚠️  dist/sw.js not found — service worker not stamped.");
		return;
	}

	// Root-relative URLs of every hashed JS/CSS asset Bun emitted this build.
	const assetUrls = result.outputs
		.filter((o) => o.kind !== "sourcemap")
		.map((o) => `/${relative(outdir, o.path).split("\\").join("/")}`)
		.filter((u) => u.endsWith(".js") || u.endsWith(".css"));

	// Content-derived version: the asset names already embed content hashes, so
	// this only changes when the build output changes (deterministic, no clock).
	const buildVersion = createHash("sha256")
		.update([...assetUrls].sort().join("\n"))
		.digest("hex")
		.slice(0, 12);

	const precacheUrls = ["/", "/manifest.webmanifest", ...assetUrls];

	let sw = await Bun.file(swPath).text();
	sw = sw.replace("__BUILD_VERSION__", buildVersion);
	sw = sw.replace(
		/const PRECACHE_URLS = \[[^\]]*\];/,
		`const PRECACHE_URLS = ${JSON.stringify(precacheUrls)};`,
	);
	await Bun.write(swPath, sw);

	console.log(`   SW version:  ${buildVersion} (${assetUrls.length} assets)`);
}

// Ensure the production HTML contains static manifest/icon links.
// Some platforms are picky about links injected only via runtime script.
const distIndexPath = join(outdir, "index.html");
const distIndex = Bun.file(distIndexPath);
if (await distIndex.exists()) {
	const html = await distIndex.text();
	const staticPwaLinks = [
		'<link rel="manifest" href="/manifest.webmanifest" />',
		'<link rel="icon" type="image/png" sizes="32x32" href="/favicon-32.png" />',
		'<link rel="shortcut icon" type="image/png" href="/favicon-32.png" />',
		'<link rel="icon" type="image/png" sizes="192x192" href="/icon-192.png" />',
		'<link rel="icon" type="image/png" sizes="512x512" href="/icon-512.png" />',
		'<link rel="apple-touch-icon" sizes="180x180" href="/apple-touch-icon.png" />',
		// iOS PWA launch images: without an exact device-size match here iOS shows
		// a blank white screen on cold launch. Generated by `bun run splash`.
		...(await loadStartupImageLinks()),
	].join("\n    ");

	const injectionAnchor = "<title>Cash Kitty — レシート家計簿</title>";
	const withLinks = html.includes('<link rel="manifest"')
		? html
		: html.replace(
				injectionAnchor,
				`${injectionAnchor}\n    ${staticPwaLinks}`,
			);
	await Bun.write(distIndexPath, withLinks);
}

/**
 * Read the `apple-touch-startup-image` <link> tags from the splash manifest
 * (public/splash/links.json, produced by `bun run splash`). Returns [] with a
 * warning if the splash assets haven't been generated yet.
 */
async function loadStartupImageLinks(): Promise<string[]> {
	const linksFile = Bun.file(join(root, "public", "splash", "links.json"));
	if (!(await linksFile.exists())) {
		console.warn(
			"⚠️  public/splash/links.json not found — run `bun run splash`. iOS launch images skipped.",
		);
		return [];
	}
	const links: Array<{ media: string; href: string }> = await linksFile.json();
	return links.map(
		(l) =>
			`<link rel="apple-touch-startup-image" media="${l.media}" href="${l.href}" />`,
	);
}

// --- Content-Security-Policy --------------------------------------------------
// Injected into the `/*` block of dist/_headers rather than written statically,
// because it depends on build-time values:
//   - connect-src must include the configured OCR API origin.
//   - script-src whitelists the exact inline <script> blocks in index.html by
//     their SHA-256 hash, so we never need 'unsafe-inline' for scripts.
// Google Identity Services origins follow Google's published CSP guidance
// (https://developers.google.com/identity/gsi/web/guides/csp).
await injectCsp();

async function injectCsp(): Promise<void> {
	const headersPath = join(outdir, "_headers");
	if (!(await Bun.file(headersPath).exists())) {
		console.warn("⚠️  dist/_headers not found — CSP not injected.");
		return;
	}

	// Hash every attribute-less inline <script> (the module script has a `src`,
	// so it is served same-origin and covered by 'self'). The hash is computed
	// over the exact text the browser sees between the tags, read back from the
	// final dist HTML so any build-time transform is already applied.
	const finalHtml = await Bun.file(distIndexPath).text();
	const scriptHashes = [
		...finalHtml.matchAll(/<script>([\s\S]*?)<\/script>/g),
	].map(
		(m) =>
			`'sha256-${createHash("sha256")
				.update(m[1] ?? "", "utf8")
				.digest("base64")}'`,
	);

	// Allow the SPA to reach the configured OCR API origin (scheme://host:port).
	let ocrConnectSrc = "";
	const ocrUrl = process.env.BUN_PUBLIC_OCR_API_URL;
	if (ocrUrl) {
		try {
			ocrConnectSrc = ` ${new URL(ocrUrl).origin}`;
		} catch {
			console.warn(`⚠️  BUN_PUBLIC_OCR_API_URL is not a valid URL: ${ocrUrl}`);
		}
	}

	const csp = [
		"default-src 'self'",
		"base-uri 'self'",
		"object-src 'none'",
		"frame-ancestors 'none'",
		"form-action 'self'",
		// Cloudflare Pages auto-injects its Web Analytics beacon
		// (static.cloudflareinsights.com/beacon.min.js), which posts RUM data to
		// cloudflareinsights.com — both are whitelisted below.
		`script-src 'self' ${scriptHashes.join(" ")} https://accounts.google.com/gsi/client https://static.cloudflareinsights.com`,
		"style-src 'self' 'unsafe-inline' https://accounts.google.com/gsi/style",
		"img-src 'self' blob: data:",
		"font-src 'self'",
		`connect-src 'self' https://www.googleapis.com https://accounts.google.com/gsi/ https://cloudflareinsights.com${ocrConnectSrc}`,
		"frame-src https://accounts.google.com/gsi/",
		"worker-src 'self'",
		"manifest-src 'self'",
	].join("; ");

	// Insert the CSP as a header line directly under the existing `/*` rule.
	const headersText = await Bun.file(headersPath).text();
	const injected = headersText.replace(
		/^\/\*[^\S\n]*$/m,
		`/*\n  Content-Security-Policy: ${csp}`,
	);
	if (injected === headersText) {
		console.warn("⚠️  No `/*` rule in dist/_headers — CSP not injected.");
		return;
	}
	await Bun.write(headersPath, injected);
}

console.log(`✅ Built static site → ${outdir}`);
console.log(
	`   Client ID:   ${process.env.BUN_PUBLIC_GOOGLE_CLIENT_ID ? "set" : "(unset — Drive disabled)"}`,
);
console.log(
	`   OCR API URL: ${process.env.BUN_PUBLIC_OCR_API_URL || "(unset — set BUN_PUBLIC_OCR_API_URL)"}`,
);
